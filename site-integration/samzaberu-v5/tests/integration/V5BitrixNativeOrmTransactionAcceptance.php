/**
 * STAGING-ONLY: prove that native Bitrix ORM and Application::getConnection()
 * share a physical InnoDB transaction by testing read-your-writes and ROLLBACK
 * in both directions on ONE dedicated synthetic probe table.
 *
 * This does NOT run the SMS router, modify b_user/b_sec_user, or register hooks.
 * Production and any database not explicitly named evrasia_v5_test_* are denied.
 */

namespace Evrasia\Samzaberu\V5\Tests\Integration;

use RuntimeException;
use Throwable;

function output(string $text): void
{
    echo $text . "\n";
}

function check(bool $condition, string $message): void
{
    if (!$condition) {
        throw new RuntimeException($message);
    }
}

function observedRow(object $connection, string $marker): ?array
{
    // Marker is freshly generated by random_bytes and verified as lowercase hex.
    check(preg_match('/\A[a-f0-9]{64}\z/D', $marker) === 1, 'Invalid test marker');
    $result = $connection->query(
        "SELECT MARKER, ORIGIN FROM ev_v5_native_tx_probe WHERE MARKER = '" . $marker . "' LIMIT 2"
    );
    check(is_object($result) && method_exists($result, 'fetch'), 'Native SELECT result unavailable');
    $first = $result->fetch();
    $extra = $result->fetch();
    check($extra === false || $extra === null, 'Duplicate synthetic test marker');
    return is_array($first) ? $first : null;
}

function observedOrmRow(string $marker): ?array
{
    $result = V5NativeTxProbeTable::getList([
        'select' => ['MARKER', 'ORIGIN'],
        'filter' => ['=MARKER' => $marker],
        'limit' => 2,
    ]);
    check(is_object($result) && method_exists($result, 'fetch'), 'ORM SELECT result unavailable');
    $first = $result->fetch();
    $extra = $result->fetch();
    check($extra === false || $extra === null, 'Duplicate ORM synthetic marker');
    return is_array($first) ? $first : null;
}

/**
 * Read only the actual native MySQL transaction/session state, never SQL write.
 * Return null on connection/identity changes or unknown driver behavior.
 * @return array{id:string,active:bool}|null
 */
function nativeSessionState(object $connection, string $schema, string $dbHost): ?array
{
    try {
        $result = $connection->query(
            'SELECT DATABASE() AS schema_name, @@hostname AS server_hostname, '
            . 'CONNECTION_ID() AS connection_id, '
            . '@@session.autocommit AS autocommit_value, '
            . '@@session.in_transaction AS in_transaction_value'
        );
        if (!is_object($result) || !method_exists($result, 'fetch')) {
            return null;
        }
        $row = $result->fetch();
        if (!is_array($row) || $result->fetch() !== false
            || ($row['schema_name'] ?? null) !== $schema
            || ($row['server_hostname'] ?? null) !== $dbHost
            || !in_array($row['autocommit_value'] ?? null, [1, '1'], true)
            || !in_array($row['in_transaction_value'] ?? null, [0, '0', 1, '1'], true)
        ) {
            return null;
        }
        $rawId = $row['connection_id'] ?? null;
        if (!(is_int($rawId) || is_string($rawId))
            || preg_match('/\A[1-9][0-9]*\z/D', (string)$rawId) !== 1
        ) {
            return null;
        }
        return ['id' => (string)$rawId,
            'active' => (string)$row['in_transaction_value'] === '1'];
    } catch (Throwable) {
        return null;
    }
}

