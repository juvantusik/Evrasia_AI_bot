CREATE DATABASE IF NOT EXISTS ev_v5_epoch_ci;
USE ev_v5_epoch_ci;

CREATE TABLE ev_samzaberu_auth_state (
  USER_ID INT NOT NULL PRIMARY KEY,
  AUTH_EPOCH BIGINT NOT NULL,
  PHONE_EVENT_VERSION BIGINT NOT NULL DEFAULT 0,
  PHONE_BINDING_HMAC CHAR(64) NULL
) ENGINE=InnoDB;

CREATE TABLE b_user_phone_auth (
  USER_ID INT NOT NULL PRIMARY KEY,
  PHONE_NUMBER VARCHAR(32) NOT NULL,
  OTP_SECRET TEXT NULL,
  ATTEMPTS INT NULL,
  CONFIRMED CHAR(1) NULL,
  DATE_SENT DATETIME NULL
) ENGINE=InnoDB;

CREATE TABLE b_sec_recovery_codes (
  ID INT NOT NULL PRIMARY KEY,
  USER_ID INT NOT NULL,
  CODE VARCHAR(128) NOT NULL,
  USED VARCHAR(1) NOT NULL,
  USING_DATE DATETIME NULL,
  USING_IP VARCHAR(45) NULL
) ENGINE=InnoDB;

